/** 前三号以外の土地の定額負担金（20万円）。施行令第5条第1項第4号。 */
export const DEFAULT_FUTANKIN = 200_000;

export interface FutankinCalcResult {
  /** 適用された階層の単価（円/㎡）。定額の場合は null */
  ratePerSqm: number | null;
  /** 適用された階層の基礎額（円）。定額の場合は null */
  baseAmount: number | null;
  /** 端数処理前の金額（円） */
  rawAmount: number;
  /** 千円未満を切り捨てた負担金（円） */
  futankin: number;
  /** 適用階層の説明（例: 「100㎡超 200㎡以下」） */
  tierLabel: string;
}

/** 階層ラベル（政令の地積区分表記に合わせる）。minArea は直前階層の上限。 */
function tierLabelOf(tier: FutankinTier, index: number, tiers: readonly FutankinTier[]): string {
  const lower = index === 0 ? 0 : (tiers[index - 1].maxArea ?? 0);
  if (tier.maxArea === null) {
    return `${lower?.toLocaleString() ?? ""}㎡超（上限なし）`;
  }
  return lower === 0
    ? `〜${tier.maxArea.toLocaleString()}㎡以下`
    : `${lower.toLocaleString()}㎡超〜${tier.maxArea.toLocaleString()}㎡以下`;
}

/**
 * 負担金を算定する（施行令第5条）。純関数（server/client両方可）。
 * 千円未満の端数は切り捨て（同条第2項）。
 */
export function calcFutankin(
  category: KokkoLandCategory,
  areaSqm: number,
): FutankinCalcResult {
  if (category === "sonota") {
    return {
      ratePerSqm: null,
      baseAmount: null,
      rawAmount: DEFAULT_FUTANKIN,
      futankin: DEFAULT_FUTANKIN,
      tierLabel: "定額（面積にかかわらず）",
    };
  }
  const def = FUTANKIN_TABLE.find((entry) => entry.key === category)!;
  const clamped = Math.max(0, Math.round(areaSqm));
  const tierIndex = def.tiers.findIndex(
    (entry) => entry.maxArea === null || clamped <= entry.maxArea,
  );
  const tier = def.tiers[tierIndex] ?? def.tiers[def.tiers.length - 1];
  const raw = clamped * tier.ratePerSqm + tier.baseAmount;
  return {
    ratePerSqm: tier.ratePerSqm,
    baseAmount: tier.baseAmount,
    rawAmount: raw,
    futankin: Math.floor(raw / 1000) * 1000,
    tierLabel: tierLabelOf(tier, tierIndex === -1 ? def.tiers.length - 1 : tierIndex, def.tiers),
  };
}

